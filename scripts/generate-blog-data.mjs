import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import matter from 'gray-matter';

// Mantener la misma barrera de seguridad del runtime durante la generación.
matter.engines.javascript = {
  parse() {
    throw new Error('JavaScript frontmatter is not supported (CVE-2026-78847)');
  },
  stringify() {
    throw new Error('JavaScript frontmatter is not supported');
  },
};
matter.engines.js = matter.engines.javascript;

const scriptsDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectDirectory = path.dirname(scriptsDirectory);
const postsDirectory = path.join(projectDirectory, 'content', 'blog');
const outputPath = path.join(projectDirectory, 'src', 'lib', 'blog-data.generated.js');

const posts = fs
  .readdirSync(postsDirectory)
  .filter((fileName) => fileName.endsWith('.md'))
  .sort()
  .map((fileName) => {
    const slug = fileName.replace(/\.md$/, '');
    const { data, content } = matter(fs.readFileSync(path.join(postsDirectory, fileName), 'utf8'));

    return {
      slug,
      title: data.title || 'Sin título',
      date: data.date || '',
      updated: data.updated,
      author: data.author || 'ArrendadorCO',
      excerpt: data.excerpt || '',
      description: data.description || '',
      category: data.category,
      tags: data.tags,
      sources: data.sources,
      featured: data.featured,
      canonical: data.canonical,
      legalReviewDate: data.legalReviewDate,
      draft: data.draft === true,
      content,
    };
  });

const output = `// Generated by scripts/generate-blog-data.mjs. Do not edit manually.\nexport const BLOG_POSTS = ${JSON.stringify(posts, null, 2)};\n`;
fs.writeFileSync(outputPath, output, 'utf8');
